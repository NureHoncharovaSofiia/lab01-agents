PATTERNS = {
    "singleton": (
        "Singleton — породжувальний патерн. Забезпечує єдиний екземпляр "
        "класу та глобальну точку доступу до нього."
    ),
    "factorymethod": (
        "Factory Method — породжувальний патерн. Визначає інтерфейс "
        "створення об'єкта, а вибір конкретного класу залишає підкласам."
    ),
    "abstractfactory": (
        "Abstract Factory — породжувальний патерн. Створює сімейства "
        "пов'язаних об'єктів без зазначення їхніх конкретних класів."
    ),
    "adapter": (
        "Adapter — структурний патерн. Перетворює інтерфейс об'єкта "
        "на очікуваний клієнтом, щоб несумісні інтерфейси могли співпрацювати."
    ),
    "decorator": (
        "Decorator — структурний патерн. Динамічно додає об'єкту "
        "обов'язки, обгортаючи його в інший об'єкт."
    ),
    "observer": (
        "Observer — поведінковий патерн. Встановлює залежність "
        "один-до-багатьох: зміна стану об'єкта сповіщає його спостерігачів."
    ),
    "strategy": (
        "Strategy — поведінковий патерн. Інкапсулює сімейство алгоритмів "
        "і дає змогу замінювати їх без зміни коду клієнта."
    ),
}


def lookup_pattern(name: str) -> str:
    """Повертає перевірений опис одного патерну GoF за назвою.

    Використовуй для конкретних назв, наприклад Observer або Factory Method.
    Регістр, пробіли, дефіси й підкреслення не впливають на пошук.
    Якщо назви немає в довіднику, повертає повідомлення з NOT_FOUND.
    """
    key = "".join(name.lower().replace("-", " ").replace("_", " ").split())
    return PATTERNS.get(key, f"NOT_FOUND: патерн {name!r} відсутній.")
